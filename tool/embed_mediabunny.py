#!/usr/bin/env python3
"""Embeds a Mediabunny browser bundle into lib/src/web/mediabunny_source.dart.

Usage: python3 tool/embed_mediabunny.py <path/to/mediabunny.min.mjs> <version>

The bundle comes from the `mediabunny` npm package (dist/bundles/
mediabunny.min.mjs). It is embedded as a Dart string so that only web builds,
which are the only ones importing the web plugin, carry it; mobile and desktop
apps do not grow. Mediabunny is MPL-2.0: the bundle keeps its license header,
and the source is at https://github.com/Vanilagy/mediabunny.
"""
import pathlib
import sys

bundle_path, version = sys.argv[1], sys.argv[2]
source = pathlib.Path(bundle_path).read_text(encoding="utf-8")
if "'''" in source:
    sys.exit("The bundle contains ''' and cannot be embedded as a raw string.")

out = pathlib.Path(__file__).resolve().parent.parent / "lib/src/web/mediabunny_source.dart"
out.write_text(
    "// GENERATED by tool/embed_mediabunny.py. Do not edit by hand.\n"
    "//\n"
    f"// Mediabunny {version} (https://github.com/Vanilagy/mediabunny), the\n"
    "// minified ES module from the npm package. Mozilla Public License 2.0; the\n"
    "// license header is kept at the top of the string, and the source code is\n"
    "// available at the link above.\n"
    "// ignore_for_file: prefer_single_quotes\n"
    "\n"
    "/// The Mediabunny version embedded in [mediabunnySource].\n"
    f"const String mediabunnyVersion = '{version}';\n"
    "\n"
    "/// The Mediabunny ES module, loaded through a blob: URL on first use.\n"
    "const String mediabunnySource = r'''" + source + "''';\n",
    encoding="utf-8",
)
print(f"wrote {out} ({len(source)} chars)")
